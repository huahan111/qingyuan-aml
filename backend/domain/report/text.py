"""报告正文：中英文文字组织，不负责取数。"""

def _fmt(n):
    return f"{n:,.0f}"


def _lc(text):
    """句中嵌入的小写化：只处理首字母大写的普通词，缩写（OTC/GmbH）保持原样。"""
    t = (text or "").strip()
    if len(t) > 1 and t[0].isupper() and t[1].islower():
        return t[0].lower() + t[1:]
    return t


def _sentence_value(text):
    """作为句末取值时去掉自带句点，避免出现两个句号。"""
    return (text or "").strip().rstrip(".")


def build_text(c):
    """c 为 build_report 组装的上下文字典，返回 (中文正文, 英文正文)。"""
    cn = (
        f"一、客户基本情况：{c['name']}，{c['age']} 岁，{c['occupation']}，"
        f"{c['open_date']} 在本机构开户，当前风险等级为{c['risk']}。\n"
        f"二、可疑交易情况：{c['start']} 至 {c['end']}，该客户共发生 {c['tx_count']} 笔交易，"
        f"累计转入/存入 {_fmt(c['in_total'])} 元，累计转出/支取 {_fmt(c['out_total'])} 元；"
        f"主要交易对手为 {c['top_cp']}，交易渠道涉及 {c['channel_text']}。\n"
        f"三、分析判断：{c['numbered']}\n"
        f"四、处置情况：规则引擎命中 {c['trig']}；AI 诊断结论为「{c['conclusion']}」，"
        f"可疑类型为 {c['type_no']} {c['type_name']}。本报告第 21、22 项由 AI 生成，"
        f"其余要素由系统带出或待人工补充，须经反洗钱专岗逐项核实修订后报送。"
    )

    conclusion_en = {"拦截": "Suspicious — report for filing", "放行": "No suspicion identified",
                     "人工复核": "Manual review required"}.get(
        c["conclusion"], "Manual review required")
    # 英文正文只引用译名表覆盖的取值：业务数据（姓名/职业/风险等级/可疑类型）走 i18n 译名，
    # 类型若未收录则整段不带括号，绝不把中文塞进英文句子。
    type_en = c.get("type_en") or ""
    type_part = f" ({type_en})" if type_en else ""
    # 第三段随结论变化：放行案例不能写成"存在重大偏离"，否则英文正文与中文结论自相矛盾
    analysis_en = {
        "拦截": ("The transaction pattern materially deviates from the customer's declared "
                 "profile and business."),
        "人工复核": ("The transaction pattern shows points requiring verification against the "
                     "customer's declared profile and business."),
        "放行": ("No material deviation from the customer's declared profile and business was "
                 "identified."),
    }.get(c["conclusion"], "The transaction pattern requires verification.")
    en = (
        f"I. Customer profile: {c['name_en']}, {c['age']} years old, "
        f"{_lc(c['occupation_en'])}; account opened {c['open_date']}; "
        f"current risk level: {c['risk_en']}.\n"
        f"II. Suspicious transactions: {c['tx_count']} transactions between "
        f"{c['start']} and {c['end']}, "
        f"total inflow CNY {_fmt(c['in_total'])}, total outflow CNY {_fmt(c['out_total'])}; "
        f"main counterparty: {_sentence_value(c['top_cp_en'])}.\n"
        f"III. Analysis: {analysis_en} The detailed analysis is provided in elements 21 and 22 "
        f"of this report{type_part}.\n"
        f"IV. Disposition: Rule engine hits: {', '.join(c['hit_ids']) or 'none'}; "
        f"AI conclusion: {conclusion_en}. This draft was generated by the system and must be "
        f"verified and revised by the AML officer before filing."
    )
    return cn, en
