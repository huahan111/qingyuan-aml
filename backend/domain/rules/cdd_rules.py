"""CDD 条线规则：客户身份不明/证件缺失（R017）。

业务依据（本项目法规库原文，已逐条核对）：
- 《反洗钱法》(2025) 第二十八条：金融机构不得为身份不明的客户提供服务或者与其进行交易，
  不得为客户开立匿名账户或者假名账户。
- 11 号令（客户尽职调查管理办法，2026-01-01 施行）第八条：同一句禁止性规定。
- 11 号令第四十一条（一）：客户拒绝提供有效身份证件或者其他身份证明文件的，应当向
  中国反洗钱监测分析中心报告；该条末款明确此类报告依照大额交易和可疑交易报告的规定执行。

与制裁名单规则（R005）的关系：身份不明户不属于"制裁/涉恐名单命中"，也不属于对照表
16 类中任何一类（那 16 类全是"钱怎么走"的交易型特征）。因此本规则独立于 R005，
官方类型不走 16 类，由覆盖矩阵"无法归类"出口承接。
"""
from .registry import rule


@rule("R017")
def check_r017(txs, cust, params):
    """客户身份不明/证件缺失：前台拒办拒交易，并按 11 号令第四十一条（一）报送。"""
    name = (cust.get("name") or "").strip()
    missing = []
    if not name:
        missing.append("客户姓名缺失")
    # 仅在显式提供了证件字段但为空时判定缺失：
    # 演示案例不携带证件字段，不因此触发（避免把"没采集"误判成"身份不明"）。
    for key, label in (("id_type", "证件类型"), ("id_no", "证件号码")):
        if key in cust and not str(cust.get(key) or "").strip():
            missing.append(f"{label}缺失")
    if not missing:
        return None
    return {
        "triggered": True,
        "desc": (f"客户身份不明（{'；'.join(missing)}）：不得为其提供服务或与其交易"
                 f"（反洗钱法第28条、11号令第8条）；应按 11 号令第四十一条（一）"
                 f"作为 CDD 条线可疑行为向反洗钱监测分析中心报告"),
        "params_found": {"missing": missing},
    }
